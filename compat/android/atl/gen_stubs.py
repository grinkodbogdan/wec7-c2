#!/usr/bin/env python3
"""Emit weak JNI stubs for every native method in a jar of classes.

    gen_stubs.py CLASSES.jar OUT.c

Each stub logs its name once and returns zero/null. The real
implementations in the Flare backend (and the reused ATL sources) are
strong symbols and replace the stubs at link time; whatever is left is the
part of the Android framework that has no native backing on Flare yet.
"""
import re
import subprocess
import sys
import zipfile

jar, out = sys.argv[1:3]
classes = [n[:-6].replace("/", ".") for n in zipfile.ZipFile(jar).namelist() if n.endswith(".class")]


def mangle(s):
    r = []
    for ch in s:
        if ch == "/":
            r.append("_")
        elif ch == "_":
            r.append("_1")
        elif ch == ";":
            r.append("_2")
        elif ch == "[":
            r.append("_3")
        elif ch.isalnum() and ord(ch) < 128:
            r.append(ch)
        else:
            r.append("_0%04x" % ord(ch))
    return "".join(r)


JT = {"Z": "jboolean", "B": "jbyte", "C": "jchar", "S": "jshort", "I": "jint", "J": "jlong",
      "F": "jfloat", "D": "jdouble", "V": "void"}


def params(desc):
    inner = desc[1:desc.index(")")]
    out, i = [], 0
    while i < len(inner):
        j = i
        while inner[j] == "[":
            j += 1
        if inner[j] == "L":
            j = inner.index(";", j)
        out.append(inner[i:j + 1])
        i = j + 1
    return out


def ctype(t):
    return JT.get(t, "jobject") if len(t) == 1 else "jobject"


natives = []  # (class, name, desc, static)
for i in range(0, len(classes), 200):
    txt = subprocess.run(["javap", "-p", "-s", "-cp", jar] + classes[i:i + 200],
                         capture_output=True, text=True, check=True).stdout
    cls = None
    lines = txt.splitlines()
    for k, line in enumerate(lines):
        m = re.match(r'^(?:Compiled from .*)?$', line)
        m = re.match(r'^.*\b(?:class|interface|enum) ([\w.$]+)', line)
        if m and not line.startswith(" "):
            cls = m.group(1)
            continue
        if " native " in line and "(" in line:
            name = re.search(r'([\w$]+)\(', line).group(1)
            desc = lines[k + 1].strip().split("descriptor: ")[1]
            natives.append((cls, name, desc, " static " in line))

count = {}
for c, n, d, s in natives:
    count[(c, n)] = count.get((c, n), 0) + 1

with open(out, "w") as f:
    f.write("/* generated by gen_stubs.py: weak stubs for unimplemented natives */\n"
            "#include <jni.h>\n#include <stdio.h>\n#define STUB(n) static int once; if (!once++) fprintf(stderr, \"atl: stub %s\\n\", n)\n"
            "jlong flare_generic_widget(JNIEnv *env, jobject view);\n")
    for c, n, d, s in natives:
        sym = "Java_" + mangle(c.replace(".", "/")) + "_" + mangle(n)
        if count[(c, n)] > 1:
            sym += "__" + mangle(d[1:d.index(")")])
        ret = d[d.index(")") + 1:]
        rt = ctype(ret) if ret[0] != "[" else "jobject"
        args = ", ".join(["JNIEnv *env", "jclass cls" if s else "jobject self"] +
                         ["%s a%d" % (ctype(p), i) for i, p in enumerate(params(d))])
        body = "" if rt == "void" else " return 0;"
        if n == "native_constructor" and ret == "J" and d.startswith("(Landroid/content/Context;"):
            # a widget without a native backend yet: a plain view node, so
            # it lays out, draws its background and children, and gets input
            body = " return flare_generic_widget(env, self);"
        f.write('__attribute__((weak)) %s %s(%s) { STUB("%s.%s");%s }\n' % (rt, sym, args, c, n, body))
print("gen_stubs.py: %d natives" % len(natives))
